// Generates src/styles/dark-palette.css — dark-mode equivalents for Tailwind's
// light pastel palette classes (bg-rose-50, border-indigo-200, from-emerald-50,
// text-violet-800, …). Many older components use those without `dark:`
// variants, so in dark mode they rendered as bright white/pastel blocks with
// dark text. Rules use `:where(.dark)` so they sit at plain-utility
// specificity: they beat the light class (they come later) but any explicit
// `dark:` variant a component sets still wins.
//
// Only classes actually used in src/ get a rule, so the output stays small;
// `pnpm build` re-runs this first, so new usages are always covered.
//
//   node scripts/gen-dark-palette.mjs
import colors from "tailwindcss/colors.js";
import { writeFileSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : /\.(tsx?|jsx?)$/.test(name) ? [p] : [];
  });
}

const HUES = ["red", "rose", "pink", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia"];
const NEUTRALS = ["slate", "gray", "zinc", "neutral", "stone"];

const rgb = (hex) => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(" ");
};
const esc = (cls) => cls.replace(/[:/.]/g, (c) => `\\${c}`);
const round = (n) => Math.round(n * 1000) / 1000;

// Tint strength for each light shade, used for backgrounds/gradients/borders.
const BG_ALPHA = { 50: 0.1, 100: 0.14, 200: 0.2 };
const BORDER_ALPHA = { 50: 0.18, 100: 0.22, 200: 0.3, 300: 0.4 };
const TEXT_MAP = { 700: 300, 800: 200, 900: 100, 950: 100 };

const rules = [];
const add = (selector, body) => rules.push(`${selector}{${body}}`);

function bgValue(color, shade, mult = 1) {
  if (NEUTRALS.includes(color)) {
    const a = { 50: 0.4, 100: 0.7, 200: 1 }[shade] * mult;
    return `hsl(var(--muted) / ${round(a)})`;
  }
  return `rgb(${rgb(colors[color][500])} / ${round(BG_ALPHA[shade] * mult)})`;
}
function borderValue(color, shade, mult = 1) {
  if (NEUTRALS.includes(color)) return `hsl(var(--border) / ${round(mult)})`;
  return `rgb(${rgb(colors[color][500])} / ${round(BORDER_ALPHA[shade] * mult)})`;
}
function textValue(color, shade) {
  if (NEUTRALS.includes(color)) return shade >= 800 ? "hsl(var(--foreground))" : "hsl(var(--muted-foreground))";
  return `rgb(${rgb(colors[color][TEXT_MAP[shade]])})`;
}

const TOKEN = /(?<![\w:-])(?:hover:)?(?:bg|border|from|via|to|text)-[a-z]+-\d{2,3}(?:\/\d+)?(?![\w-])/g;
const used = new Set();
for (const f of walk("src")) for (const m of readFileSync(f, "utf8").matchAll(TOKEN)) used.add(m[0]);

for (const cls of [...used].sort()) {
  const hover = cls.startsWith("hover:");
  const base = hover ? cls.slice(6) : cls;
  const [, kind, color, shadeStr, pct] = base.match(/^(bg|border|from|via|to|text)-([a-z]+)-(\d+)(?:\/(\d+))?$/) || [];
  if (!kind || !(HUES.includes(color) || NEUTRALS.includes(color))) continue;
  const shade = Number(shadeStr);
  // Hover states read a touch stronger than rest so the affordance survives.
  const mult = (pct ? Number(pct) / 100 : 1) * (hover ? 1.6 : 1);
  // `.keep-light` opts a subtree out (white print-preview sheets).
  const sel = `:where(.dark) .${esc(cls)}${hover ? ":hover" : ""}:not(:where(.keep-light, .keep-light *))`;
  if (kind === "bg" && BG_ALPHA[shade]) add(sel, `background-color:${bgValue(color, shade, mult)}`);
  else if (kind === "border" && BORDER_ALPHA[shade]) add(sel, `border-color:${borderValue(color, shade, Math.min(mult, 1.4))}`);
  else if (kind === "text" && TEXT_MAP[shade] && !hover && !pct) add(sel, `color:${textValue(color, shade)}`);
  else if ((kind === "from" || kind === "via" || kind === "to") && BG_ALPHA[shade] && !hover) {
    const v = bgValue(color, shade, mult);
    const clear = v.replace(/\/ [\d.]+\)$/, "/ 0)");
    if (kind === "from") add(sel, `--tw-gradient-from:${v} var(--tw-gradient-from-position);--tw-gradient-to:${clear} var(--tw-gradient-to-position);--tw-gradient-stops:var(--tw-gradient-from), var(--tw-gradient-to)`);
    if (kind === "via") add(sel, `--tw-gradient-to:${clear} var(--tw-gradient-to-position);--tw-gradient-stops:var(--tw-gradient-from), ${v} var(--tw-gradient-via-position), var(--tw-gradient-to)`);
    if (kind === "to") add(sel, `--tw-gradient-to:${v} var(--tw-gradient-to-position)`);
  }
}

writeFileSync(
  "src/styles/dark-palette.css",
  // Screen only: the .dark class is still set when printing, and paper is white.
  `/* Generated by scripts/gen-dark-palette.mjs — do not edit by hand. */\n@media screen {\n${rules.join("\n")}\n}\n`,
);
console.log(`${rules.length} rules`);
